# Corollary (16.18) for M_r(Z/n).


def ideal_generated(Xm, r, n):
    """Z/n-span of E_ab X E_cd, as a set of r x r tuples."""
    gens = []
    for a, b, c, d in product(range(r), repeat=4):
        Y = [[0] * r for _ in range(r)]
        Y[a][d] = Xm[b][c] % n
        gens.append(tuple(v for row in Y for v in row))
    # Z/n-module generated: Hermite form over Z with n Z^(r*r) added
    rows = [list(g) for g in gens] + [[n if k == l else 0 for l in range(r * r)]
                                     for k in range(r * r)]
    return matrix(ZZ, rows).row_module()


