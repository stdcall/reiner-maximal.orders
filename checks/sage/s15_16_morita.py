# (16.14)(v) for M_2(F_q), M_3(F_2): count one-sided ideals.
for q, r in [(2, 2), (3, 2), (4, 2), (2, 3)]:
    F = GF(q, 'u')
    els = list(F)
    vecs = list(product(els, repeat=r * r))

    def mat(t):
        return [list(t[i * r:(i + 1) * r]) for i in range(r)]

    def mul(a, b):
        A, B = mat(a), mat(b)
        return tuple(sum(A[i][k] * B[k][j] for k in range(r))
                     for i in range(r) for j in range(r))
    # right ideals correspond to subspaces W of F^r: {X : columns in W}
    # (left ideals to rows); verify by generating the right ideal of X
    rights = set()
    lefts = set()
    for X in vecs:
        RX = set()
        for Y in vecs:
            RX.add(mul(X, Y))
        rights.add(frozenset(RX))
        LX = frozenset(mul(Y, X) for Y in vecs)
        lefts.add(LX)
    # principal one-sided ideals are all one-sided ideals of M_r(F)
    nsub = {2: q + 1, 3: 2 * (q**2 + q + 1)}[r]
    proper_r = [S for S in rights if 1 < len(S) < q**(r * r)]
    proper_l = [S for S in lefts if 1 < len(S) < q**(r * r)]
    check(len(proper_r) == nsub and len(proper_l) == nsub,
          '(16.14)(v) one-sided ideals <-> subspaces')
    two = [S for S in proper_r if S in lefts]
    check(two == [], '(16.18) M_r(F) simple')

# Exercise 16.4: centres
for n in [1, 2, 3]:
    rows = []
    for (i, j) in product(range(n), repeat=2):
        Eij = E(n, i, j)
        for (a, b) in product(range(n), repeat=2):
            row = [0] * (n * n)
            for k in range(n):
                row[a * n + k] += Eij[k, b]
                row[k * n + b] -= Eij[a, k]
            rows.append(row)
    ker = matrix(QQ, rows).right_kernel()
    check(ker.dimension() == 1 and
          list(ker.basis()[0]) == identity_matrix(QQ, n).list(),
          'Exercise 16.4: centre of M_n = scalars')

