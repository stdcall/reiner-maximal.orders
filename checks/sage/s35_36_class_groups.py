"""Ideal class groups and K_0 of maximal orders (Sections 35-36).

* Exercise 35.2 (p. 314) and the definition of Cl_A R (p. 309): for the
  real quadratic fields QQ(sqrt d), squarefree 2 <= d < 60, and the totally
  real cubic fields of discriminants 49, 81, 148, 169, and every set S of
  real places: |Cl_S R| = |Cl R| 2^|S| / |sgn_S(u(R))| (PARI ray class
  groups modulo S, signs of the units), and the kernel of Cl_S R -> Cl R is
  generated by the classes of principal ideals R alpha, alpha of prescribed
  signs on S, each of order <= 2: an elementary abelian 2-group of the
  stated order.
* (35.4), (35.13)(ii), (35.14), Remark (i) after (35.14) (pp. 307-313): for
  the definite quaternion algebra A of discriminant 11 (Cl_A ZZ = 1, so
  Cl Lambda = 1 by (35.14)) a maximal order Lambda has a non-principal right
  ideal I (no element of reduced norm N(I)), and an explicit
  g in M_2(A) with I + Lambda = g Lambda^(2): so I + Lambda = Lambda + Lambda
  while I is not isomorphic to Lambda; cancellation (35.4) fails and the
  stable classes do not separate isomorphism classes without the Eichler
  condition (Swan's phenomenon).  The same for discriminant 23 (h = 3).
* (35.9) and (36.11) (pp. 310, 318): for these I and Lambda,
  [M_2(Lambda) : phi(X)] = (nr J_1 nr J_2)^4 for X = J_1 + J_2 with
  J_i in {I, Lambda}, phi(X) = [[J_1, J_2], [J_1, J_2]], so
  nr phi(X) = nr J_1 nr J_2.
* Steinitz (35.1)-(35.2) and K_0(R) = ZZ + Cl R (36.5) for R = ZZ[sqrt -5]:
  a + a = R + R for a = (2, 1 + sqrt -5) (explicit basis of a + a in K^2),
  while a + R is not free (a is not principal): [a] + [a] = [a^2] = 0 in
  Cl R = ZZ/2.

Not established: Swan's theorem (35.14) in general; the Jordan-Zassenhaus
finiteness; anything beyond the listed fields and algebras.
"""
from sage.all import (QQ, ZZ, BrandtModule, QuadraticField, QuadraticForm,
                      block_matrix, lcm, matrix, pari, vector)
import itertools
import random

N = 0


def ok(cond, msg=''):
    global N
    assert cond, msg
    N += 1


# --- Exercise 35.2 -----------------------------------------------------------
fields = ['x^2-%d' % d for d in range(2, 60) if ZZ(d).is_squarefree()]
fields += ['x^3-x^2-2*x+1', 'x^3-3*x+1', 'x^3-x^2-3*x+1', 'x^3-x^2-4*x-1']
for f in fields:
    bnf = pari('bnfinit(%s,1)' % f)
    nf = pari('(b)->b.nf')(bnf)
    r1 = int(pari('(n)->n.sign[1]')(nf))
    deg = int(pari('(n)->poldegree(n.pol)')(nf))
    ok(r1 == deg)                                   # totally real
    h = int(pari('(b)->b.no')(bnf))
    units = list(pari('(b)->concat(b.fu, [b.tu[2]])')(bnf))
    signs = [list(pari('nfeltsign')(nf, u)) for u in units]
    # elements with prescribed signs: search small integral elements
    pol = pari('(n)->n.pol')(nf)
    signed = {}
    for c in itertools.product(range(-3, 4), repeat=deg):
        alpha = pari('Mod(%s, %s)' % ('+'.join('(%d)*x^%d' % (ci, i)
                                                  for i, ci in enumerate(c)), pol))
        if alpha == 0:
            continue
        sg = tuple(int(s) for s in pari('nfeltsign')(nf, alpha))
        if 0 in sg:
            continue
        signed.setdefault(sg, alpha)
        if len(signed) == 2**r1:
            break
    ok(len(signed) == 2**r1, f)
    for S in itertools.product([0, 1], repeat=r1):
        bnr = pari('bnrinit')(bnf, [1, list(S)])
        hS = int(pari('(b)->b.no')(bnr))
        cyc = [int(c) for c in pari('(b)->b.cyc')(bnr)]
        idx = [i for i in range(r1) if S[i]]
        # the subgroup of {+-1}^S generated by the signs of the units
        gens = [tuple(int(sv[i]) for i in idx) for sv in signs]
        sub = {tuple([1] * len(idx))}
        for g in gens:
            sub |= {tuple(a * b for a, b in zip(x, g)) for x in sub}
        ok(hS * len(sub) == h * 2**len(idx), (f, S))
        # kernel of Cl_S -> Cl: classes of R alpha
        kernel = set()
        for sg, alpha in signed.items():
            v = tuple(int(c) for c in pari('bnrisprincipal')(bnr, alpha, 0))
            ok(all((2 * vi) % ci == 0 for vi, ci in zip(v, cyc)), (f, S, sg))
            kernel.add(v)
        closure = set(kernel)
        changed = True
        while changed:
            changed = False
            for x in list(closure):
                for y in list(closure):
                    z = tuple((a + b) % c for a, b, c in zip(x, y, cyc))
                    if z not in closure:
                        closure.add(z)
                        changed = True
        ok(len(closure) == hS // h, (f, S))


# --- Swan's phenomenon in definite quaternion algebras ------------------------
def lattice(rows):
    M = matrix(QQ, rows)
    den = M.denominator()
    H = (den * M).change_ring(ZZ).echelon_form(include_zero_rows=False)
    return H.change_ring(QQ) / den


def count_norm(els, value):
    G = matrix(QQ, [[(x * y.conjugate()).reduced_trace() for y in els] for x in els])
    Qf = QuadraticForm(ZZ, (G / value).change_ring(ZZ))
    return len(Qf.short_vector_list_up_to_length(2)[1])


random.seed(35)
for D in [11, 23]:
    Bm = BrandtModule(D)
    ideals = Bm.right_ideals()
    ok(len(ideals) == {11: 2, 23: 3}[D])
    O = ideals[0].right_order()
    A = O.quaternion_algebra()
    Ob = list(O.basis())
    ok(all(I.right_order() == O for I in ideals))
    nonprincipal = [I for I in ideals if count_norm(list(I.basis()), I.norm()) == 0]
    ok(len(nonprincipal) == len(ideals) - 1, D)
    for I0 in nonprincipal:
        # an integral right ideal of small norm in the class of I0:
        # J = (xbar / N(I0)) I0 for x in I0 of minimal reduced norm
        els0 = list(I0.basis())
        G0 = matrix(QQ, [[(x * y.conjugate()).reduced_trace() for y in els0]
                         for x in els0])
        Q0 = QuadraticForm(ZZ, (G0 / I0.norm()).change_ring(ZZ))
        vs = Q0.short_vector_list_up_to_length(8)
        m = min(k for k in range(1, 8) if vs[k])
        x = sum(ZZ(c) * e for c, e in zip(vs[m][0], els0))
        Ib = [x.conjugate() * e / I0.norm() for e in els0]
        nI = m
        ok(all(e in O for e in Ib) and nI > 1)              # integral, J != O
        ok(count_norm(Ib, nI) == 0, D)                      # J not principal
        # O^2 = column vectors, right O-module; g O^2 = I + O iff the
        # columns of g lie in I + O and [O^2 : g O^2] = [O : I] = nI^2.
        # nr g = nr(a) nr(d) + nr(b) nr(c) - tr(a c' d b') for
        # g = [[a, b], [c, d]] in M_2(A) (' = conjugation); search a, b in I
        # and c, d in O of small reduced norm with nr g = nI.
        def short(els, bound):
            G = matrix(QQ, [[(x * y.conjugate()).reduced_trace() for y in els]
                            for x in els])
            den = G.denominator()
            Qf = QuadraticForm(ZZ, (den * G).change_ring(ZZ))
            out = []
            for vs in Qf.short_vector_list_up_to_length(den * bound + 1)[1:]:
                for v in vs:
                    out.append(sum(ZZ(c) * x for c, x in zip(v, els)))
            return out
        # nr g = nr(d) nr(a - b u) for g = [[a, b], [c, d]], u = d^-1 c
        # (column operation), and the lattice J + J u depends only on
        # c mod dO.  For d in O of small reduced norm k and c over O/dO,
        # search x = a - b u in J + J u with nr x = nI / k (Fincke-Pohst).
        def integral_combination(gens_rows, target):
            raw = matrix(QQ, gens_rows)
            dg = lcm(raw.denominator(), vector(QQ, target).denominator())
            Mz = (dg * raw).change_ring(ZZ)
            H, U = Mz.echelon_form(transformation=True)
            nz = [i for i in range(H.nrows()) if H.row(i) != 0]
            co = H.matrix_from_rows(nz).change_ring(QQ).solve_left(
                dg * vector(QQ, target))
            if co.denominator() != 1:
                return None
            full = vector(ZZ, [0] * H.nrows())
            for i, ci in zip(nz, co):
                full[i] = ci
            return full * U

        Ds = sorted(short(Ob, 3 * nI), key=lambda e: e.reduced_norm())
        Jrows = [list(e) for e in Ib]
        found = None
        for dd in Ds:
            k = dd.reduced_norm()
            if k == 1:
                continue
            dO = lattice([list(dd * e) for e in Ob])
            reps, seen = [], []
            for cs in itertools.product(range(int(k)), repeat=4):
                c = sum(ZZ(ci) * e for ci, e in zip(cs, Ob))
                if any(dO.solve_left(vector(QQ, list(c - r))).denominator() == 1
                       for r in seen):
                    continue
                seen.append(c)
            for c in seen:
                u = dd**-1 * c
                gens = Jrows + [list(e * u) for e in Ib]
                L = lattice(gens)
                Lels = [A(list(r)) for r in L.rows()]
                t = QQ(nI) / k
                G = matrix(QQ, [[(e * f.conjugate()).reduced_trace() / t
                                 for f in Lels] for e in Lels])
                den = G.denominator()
                vs = QuadraticForm(ZZ, (den * G).change_ring(ZZ)) \
                    .short_vector_list_up_to_length(den + 1)[den]
                if not vs:
                    continue
                xel = sum(ZZ(ci) * e for ci, e in zip(vs[0], Lels))
                sol = integral_combination(gens, list(xel))
                if sol is None:
                    continue
                a1 = sum(sol[i] * Ib[i] for i in range(4))
                b1 = -sum(sol[4 + i] * Ib[i] for i in range(4))
                ok(a1 - b1 * u == xel)
                found = ((a1, c), (b1, dd))
                break
            if found:
                break
        ok(found is not None, D)
        (t1, b1), (t2, b2) = found
        images = [list(t1 * x) + list(b1 * x) for x in Ob] + \
                 [list(t2 * x) + list(b2 * x) for x in Ob]
        coords_basis = matrix(QQ, [list(x) + [0] * 4 for x in Ob] +
                                  [[0] * 4 + list(x) for x in Ob])
        ok(abs(coords_basis.solve_left(matrix(QQ, images)).det()) == nI**2)
        target = lattice([list(x) + [0] * 4 for x in Ib] + [[0] * 4 + list(x) for x in Ob])
        img = lattice(images)
        ok(img == target, D)                       # g O^2 = I + O exactly
        # (35.9) / (36.11): index of phi(X) in M_2(O)
        for J1, J2 in [(Ib, Ob), (Ib, Ib), (Ob, Ib)]:
            n1 = nI if J1 is Ib else 1
            n2 = nI if J2 is Ib else 1
            def block(r, c, x):
                v = [0] * 16
                k = 4 * (2 * r + c)
                v[k:k + 4] = list(x)
                return v
            phi = lattice([block(r, c, x) for r in range(2) for c in range(2)
                           for x in (J1 if c == 0 else J2)])
            gam = lattice([block(r, c, x) for r in range(2) for c in range(2)
                           for x in Ob])
            index = abs(gam.solve_left(phi).det())
            ok(index == (n1 * n2)**4, (D, n1, n2))

# --- Steinitz for ZZ[sqrt -5] -------------------------------------------------
K = QuadraticField(-5, 's')
s = K.gen()
R = K.maximal_order()
a = K.ideal(2, 1 + s)
ok(not a.is_principal() and (a**2).is_principal())
ab = a.basis()
found = None
for c in itertools.product(range(-2, 3), repeat=8):
    v1 = (c[0] * ab[0] + c[1] * ab[1], c[2] * ab[0] + c[3] * ab[1])
    v2 = (c[4] * ab[0] + c[5] * ab[1], c[6] * ab[0] + c[7] * ab[1])
    d = v1[0] * v2[1] - v1[1] * v2[0]
    if d != 0 and K.ideal(d) == a**2:
        found = (v1, v2)
        break
ok(found is not None)
v1, v2 = found
for comp in [0, 1]:
    ok(K.ideal(v1[comp], v2[comp]) + a == a)       # rows lie in a + a
# R v1 + R v2 = a + a: the determinant ideal equals that of a + a
ok(K.ideal(v1[0] * v2[1] - v1[1] * v2[0]) == a * a)
# a + R is not free: its determinant ideal a is not principal
ok(not a.is_principal())

print(f'ok s35_36_class_groups: {N} checks')
