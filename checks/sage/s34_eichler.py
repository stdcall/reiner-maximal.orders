# --- definite algebras: class numbers and non-principal ideals ---------------
def norm_vectors(rows_els, value):
    """Elements of the lattice spanned by rows_els with nr = value (positive)."""
    G = matrix(QQ, [[(x * y.conjugate()).reduced_trace() for y in rows_els]
                    for x in rows_els])
    nI = value
    Qf = QuadraticForm(ZZ, (G / nI).change_ring(ZZ))
    vs = Qf.short_vector_list_up_to_length(2)
    return len(vs[1])


def eichler_class_number(D):
    return (QQ(D - 1) / 12 + QQ(1 - kronecker_symbol(-4, D)) / 4
            + QQ(1 - kronecker_symbol(-3, D)) / 3)


types = {}
for D in prime_range(200):
    Bm = BrandtModule(D)
    ok(Bm.dimension() == eichler_class_number(D), D)
    ideals = Bm.right_ideals()
    principal = 0
    for I in ideals:
        els = list(I.basis())
        nI = I.norm()
        if norm_vectors(els, nI) > 0:
            principal += 1
    ok(principal == 1, D)
    types[D] = [I.left_order() for I in ideals]


def has_integral_norm_criterion(D, beta):
    for t in range(-10, 11):
        disc = t**2 - 4 * beta
        if disc >= 0:
            continue
        if kronecker_symbol(disc, D) != 1:   # D not split in QQ(sqrt disc)
            return True
    return False


