# --- Eichler's theorem for indefinite quaternion algebras over QQ -----------
def ramified(a, b):
    places = [-1] + sorted(set(Integer(2 * a * b).prime_divisors()))
    return [v for v in places if hilbert_symbol(a, b, v) == -1]


def indefinite_algebra(D):
    primes = Integer(D).prime_divisors()
    for a in [-1, -2, -3, -5, -6, -7, -10, -11, -13, 2, 3, 5]:
        for b in list(range(-200, 0)) + list(range(2, 200)):
            if Integer(b).is_squarefree():
                ram = ramified(a, b)
                if -1 not in ram and ram == primes:
                    return QuaternionAlgebra(QQ, a, b), a, b
    raise ValueError(D)


def lattice(rows):
    M = matrix(QQ, rows)
    den = M.denominator()
    H = (den * M).change_ring(ZZ).echelon_form(include_zero_rows=False)
    return H.change_ring(QQ) / den


def contains(big, small):
    return all(big.solve_left(v).denominator() == 1 for v in small.rows())


def same(L1, L2):
    return L1.nrows() == L2.nrows() and contains(L1, L2) and contains(L2, L1)


def find_norm(B, a, b, rows, targets, bound=12, any_one=False):
    """Elements x of the lattice with nr x in targets.

    The basis is LLL-reduced for the majorant x0^2 + |a| x1^2 + |b| x2^2
    + |ab| x3^2 of the norm form; for each choice of the last three
    coordinates in [-bound, bound] the quadratic equation for the first one
    is solved exactly (Python integers; the result is verified in B).
    """
    els = [B(list(r)) for r in rows]
    W = matrix(QQ, [[1, 0, 0, 0], [0, abs(a), 0, 0], [0, 0, abs(b), 0],
                    [0, 0, 0, abs(a * b)]])
    M = matrix(QQ, [list(r) for r in rows])
    G = M * W * M.transpose()
    den = G.denominator()
    U = (den * G).change_ring(ZZ).LLL_gram()
    red = [sum(U[j, i] * els[j] for j in range(4)) for i in range(4)]
    Q = matrix(QQ, 4, 4, lambda i, j:
               (red[i] * red[j].conjugate()).reduced_trace() / 2)
    d = int(Q.denominator())
    Qi = [[int(d * Q[i, j]) for j in range(4)] for i in range(4)]
    A2 = Qi[0][0]
    tg = [(int(t), d * int(t)) for t in targets]
    found = {}
    rng = range(-bound, bound + 1)
    for c1 in rng:
        for c2 in rng:
            for c3 in rng:
                cc = (c1, c2, c3)
                B1 = 2 * (Qi[0][1] * c1 + Qi[0][2] * c2 + Qi[0][3] * c3)
                C0 = sum(Qi[i + 1][j + 1] * cc[i] * cc[j]
                         for i in range(3) for j in range(3))
                for tval, dt in tg:
                    if tval in found:
                        continue
                    disc = B1 * B1 - 4 * A2 * (C0 - dt)
                    if disc < 0:
                        continue
                    sq = isqrt(disc)
                    if sq * sq != disc:
                        continue
                    for num in (-B1 + sq, -B1 - sq):
                        if num % (2 * A2) == 0:
                            c0 = num // (2 * A2)
                            x = c0 * red[0] + c1 * red[1] + c2 * red[2] + c3 * red[3]
                            ok(x.reduced_norm() == tval)
                            found[tval] = x
                            break
                if len(found) == len(tg) or (any_one and found):
                    return found
    return found


