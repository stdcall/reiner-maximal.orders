def incl(r, b, c):
    """r Lambda_b in Lambda_c for Lambda_b = [[R, b^-1], [b, R]]."""
    def sub(I, J):
        return I + J == J
    return sub(r * b**-1, c**-1) and sub(r * b, c) and sub(K.ideal(r), R1)


